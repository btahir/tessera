// Packs themes/ into installable plugins.
//
//   bun scripts/pack.ts
//
// Writes plugins/<name>/ for each theme, plugins/tessera/ holding all of them
// behind one /tessera command, and .claude-plugin/marketplace.json, the file
// that makes this repository a place to install from. Everything in plugins/
// is generated: change themes/ or runtime/ and run this again.

import { cp, mkdir, rm } from 'node:fs/promises'
import { join } from 'node:path'

import { loadThemes, root, type LoadedTheme } from './themes'

const VERSION = '1.0.0'
const pluginsDir = join(root, 'plugins')
const runtimeDir = join(root, 'runtime')

const themes = await loadThemes()

// What the runtime reads: plain data, with the scene already drawn to a string.
const themesModule = (command: string, packed: LoadedTheme[]) => {
  const data = packed.map(theme => ({
    name: theme.name,
    title: theme.title,
    tagline: theme.tagline,
    alt: theme.alt,
    words: theme.words,
    palette: theme.palette,
    glass: theme.glass,
    scene: theme.scene,
    chime: theme.chimeFile === null ? null : `chimes/${theme.name}.mp3`,
  }))

  return [
    '// Generated by scripts/pack.ts. Edit themes/ and pack again.',
    "import type { makeColors } from './make-colors.js'",
    '',
    'export type Theme = {',
    '  name: string',
    '  title: string',
    '  tagline: string',
    '  alt: string',
    '  words: string[]',
    '  palette: Parameters<typeof makeColors>[0]',
    '  glass: { blur: number; opacity: number }',
    '  scene: string',
    '  chime: string | null',
    '}',
    '',
    `export const COMMAND = ${JSON.stringify(command)}`,
    '',
    `export const THEMES: Theme[] = ${JSON.stringify(data, null, 2)}`,
    '',
  ].join('\n')
}

const writePlugin = async (name: string, description: string, packed: LoadedTheme[]) => {
  const dir = join(pluginsDir, name)

  await mkdir(join(dir, '.claude-plugin'), { recursive: true })
  await mkdir(join(dir, 'hooks'), { recursive: true })

  await Bun.write(
    join(dir, '.claude-plugin/plugin.json'),
    `${JSON.stringify({ name, version: VERSION, description, author: { name: 'Tessera' }, license: 'MIT' }, null, 2)}\n`,
  )
  await Bun.write(join(dir, 'hooks/hooks.json'), '{ "modules": ["./register.tsx"] }\n')
  await Bun.write(join(dir, 'hooks/themes.ts'), themesModule(name, packed))

  for (const file of ['register.tsx', 'make-colors.js', 'make-colors.d.ts']) {
    await cp(join(runtimeDir, file), join(dir, 'hooks', file))
  }

  for (const theme of packed) {
    if (theme.chimeFile !== null) {
      await mkdir(join(dir, 'chimes'), { recursive: true })
      await cp(theme.chimeFile, join(dir, 'chimes', `${theme.name}.mp3`))
    }
  }

  return { name, source: `./plugins/${name}`, description }
}

await rm(pluginsDir, { recursive: true, force: true })

const entries = [
  await writePlugin(
    'tessera',
    `Tessera: all ${themes.length} themes in one plugin. Type /tessera and a name to change the room.`,
    themes,
  ),
]

for (const theme of themes) {
  entries.push(await writePlugin(theme.name, `${theme.title} (${theme.meaning}). ${theme.tagline}`, [theme]))
}

await mkdir(join(root, '.claude-plugin'), { recursive: true })
await Bun.write(
  join(root, '.claude-plugin/marketplace.json'),
  `${JSON.stringify(
    {
      name: 'tessera',
      description: 'Rooms to read in. Sixteen themes for the Claude Code desktop app, each one still while you read.',
      owner: { name: 'Tessera' },
      plugins: entries,
    },
    null,
    2,
  )}\n`,
)

console.log(`packed ${entries.length} plugins: ${entries.map(entry => entry.name).join(', ')}`)
